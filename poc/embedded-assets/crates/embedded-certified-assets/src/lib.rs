//! Runtime half of embedded certified assets.
//!
//! The companion `embedded-certified-assets-build` crate runs in the canister's
//! `build.rs`: it prepares a `dist/` directory, resolves every route, and
//! **precomputes every certified response hash**. It then generates a
//! `static ASSETS: Assets` whose bodies are `include_bytes!`'d into the Wasm.
//!
//! This crate only has to:
//!
//! 1. [`init`]: insert the precomputed (expression hash, response hash) leaves
//!    into an [`HttpCertificationTree`] and set the canister's certified data to
//!    its root. Nothing is hashed here except tree nodes, so init cost does not
//!    grow with asset size.
//! 2. [`http_request`]: pick the route (exact path, else the longest wildcard
//!    prefix — the same rule the HTTP gateway's v2 verification uses), pick an
//!    encoding, and attach the witness as the `IC-Certificate` header.
//!
//! Nothing changes after install, so there is no update path at all. The tree
//! lives on the heap and is rebuilt from the static data on every
//! `init`/`post_upgrade`.
//!
//! ```ignore
//! embedded_certified_assets::include_assets!();
//!
//! #[ic_cdk::init]
//! #[ic_cdk::post_upgrade]
//! fn init() { embedded_certified_assets::init(&ASSETS); }
//!
//! #[ic_cdk::query]
//! fn http_request(req: HttpRequest) -> HttpResponse<'static> {
//!     embedded_certified_assets::http_request(req)
//! }
//! ```

use ic_http_certification::{
    HttpCertification, HttpCertificationPath, HttpCertificationTree, HttpCertificationTreeEntry,
    StatusCode, utils::add_v2_certificate_header,
};
use std::cell::RefCell;
use std::collections::HashMap;

pub use ic_http_certification::{HttpRequest, HttpResponse};

/// Includes the code generated by `embedded_certified_assets_build::embed`,
/// which defines `static ASSETS: embedded_certified_assets::Assets`.
#[macro_export]
macro_rules! include_assets {
    () => {
        include!(concat!(env!("OUT_DIR"), "/embedded_certified_assets.rs"));
    };
}

/// Everything baked in at compile time.
#[derive(Debug)]
pub struct Assets {
    pub routes: &'static [Route],
}

/// A certified path: an exact URL path, or a wildcard prefix (`/blog/` covers
/// every path under it; `/` covers everything).
#[derive(Debug)]
pub struct Route {
    pub path: &'static str,
    pub wildcard: bool,
    /// One per available encoding, in server preference order (br, gzip, identity).
    pub responses: &'static [Response],
}

/// One fully-formed certified response. `headers` already include the
/// `IC-CertificateExpression` header; the hashes were computed at build time
/// over exactly these headers, `status` and `body`.
#[derive(Debug)]
pub struct Response {
    pub encoding: Encoding,
    pub status: u16,
    pub headers: &'static [(&'static str, &'static str)],
    pub body: &'static [u8],
    pub cel_expr_hash: [u8; 32],
    pub response_hash: [u8; 32],
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Encoding {
    Identity,
    Gzip,
    Brotli,
}

impl Encoding {
    fn token(self) -> &'static str {
        match self {
            Encoding::Identity => "identity",
            Encoding::Gzip => "gzip",
            Encoding::Brotli => "br",
        }
    }
}

/// The certified routing table built from [`Assets`]. Pure (no system API), so
/// it can be driven natively in tests with a fake certificate.
pub struct Router {
    tree: HttpCertificationTree,
    exact: HashMap<&'static str, &'static Route>,
    /// Sorted longest-first, so the first prefix match is the most specific.
    wildcards: Vec<&'static Route>,
}

impl Router {
    pub fn new(assets: &'static Assets) -> Self {
        let mut tree = HttpCertificationTree::default();
        let mut exact = HashMap::new();
        let mut wildcards = Vec::new();
        for route in assets.routes {
            for response in route.responses {
                tree.insert(&entry(route, response));
            }
            if route.wildcard {
                wildcards.push(route);
            } else {
                exact.insert(route.path, route);
            }
        }
        wildcards.sort_by_key(|r| std::cmp::Reverse(r.path.len()));
        Self {
            tree,
            exact,
            wildcards,
        }
    }

    /// The value to pass to `certified_data_set`.
    pub fn root_hash(&self) -> [u8; 32] {
        self.tree.root_hash()
    }

    pub fn serve(&self, req: &HttpRequest, data_certificate: &[u8]) -> HttpResponse<'static> {
        let Ok(path) = req.get_path() else {
            return uncertified(400, "malformed request path");
        };
        let Some(route) = self.resolve(&path) else {
            // Unreachable for a table produced by the build crate, which always
            // certifies a root `/` wildcard.
            return uncertified(404, "not found");
        };
        let response = pick_encoding(route.responses, accepted_encodings(req));

        let mut out = HttpResponse::builder()
            .with_status_code(StatusCode::from_u16(response.status).expect("valid status"))
            .with_headers(
                response
                    .headers
                    .iter()
                    .map(|(k, v)| (k.to_string(), v.to_string()))
                    .collect(),
            )
            .with_body(response.body)
            .build();
        let entry = entry(route, response);
        let witness = self
            .tree
            .witness(&entry, &path)
            .expect("resolved route is valid for the request path");
        add_v2_certificate_header(
            data_certificate,
            &mut out,
            &witness,
            &entry.path.to_expr_path(),
        );
        out
    }

    /// Exact match first, then the longest wildcard prefix. This must mirror
    /// what the gateway accepts: it rejects a wildcard response if an exact
    /// entry or a more specific wildcard exists for the path.
    fn resolve(&self, path: &str) -> Option<&'static Route> {
        self.exact.get(path).copied().or_else(|| {
            self.wildcards
                .iter()
                .find(|r| path.starts_with(r.path))
                .copied()
        })
    }
}

fn entry(route: &Route, response: &Response) -> HttpCertificationTreeEntry<'static> {
    let path = if route.wildcard {
        HttpCertificationPath::wildcard(route.path)
    } else {
        HttpCertificationPath::exact(route.path)
    };
    let cert =
        HttpCertification::response_only_prehashed(response.cel_expr_hash, response.response_hash);
    HttpCertificationTreeEntry::new(path, cert)
}

/// Encodings the client accepts (ignoring `q` weights except `q=0`).
fn accepted_encodings(req: &HttpRequest) -> Vec<&'static str> {
    let mut out = vec![];
    for (name, value) in req.headers() {
        if !name.eq_ignore_ascii_case("accept-encoding") {
            continue;
        }
        for item in value.split(',') {
            let mut parts = item.split(';').map(str::trim);
            let token = parts.next().unwrap_or_default();
            let refused = parts.any(|p| p.replace(' ', "").eq_ignore_ascii_case("q=0"));
            if refused {
                continue;
            }
            for enc in [Encoding::Brotli, Encoding::Gzip, Encoding::Identity] {
                if token.eq_ignore_ascii_case(enc.token()) {
                    out.push(enc.token());
                }
            }
        }
    }
    out
}

/// Server preference (the order `responses` is stored in): the first encoding
/// the client accepts; identity is always acceptable; else whatever exists.
fn pick_encoding(responses: &'static [Response], accepted: Vec<&str>) -> &'static Response {
    responses
        .iter()
        .find(|r| r.encoding == Encoding::Identity || accepted.contains(&r.encoding.token()))
        .unwrap_or(&responses[0])
}

fn uncertified(status: u16, msg: &'static str) -> HttpResponse<'static> {
    HttpResponse::builder()
        .with_status_code(StatusCode::from_u16(status).expect("valid status"))
        .with_body(msg.as_bytes())
        .build()
}

thread_local! {
    static ROUTER: RefCell<Option<Router>> = const { RefCell::new(None) };
}

/// Build the certification tree and set certified data. Call from both
/// `#[init]` and `#[post_upgrade]`.
pub fn init(assets: &'static Assets) {
    let router = Router::new(assets);
    ic_cdk::api::certified_data_set(router.root_hash());
    ROUTER.with_borrow_mut(|r| *r = Some(router));
}

/// The body of the canister's `http_request` query.
pub fn http_request(req: HttpRequest) -> HttpResponse<'static> {
    let certificate = ic_cdk::api::data_certificate().unwrap_or_default();
    ROUTER.with_borrow(|r| {
        r.as_ref()
            .expect("embedded_certified_assets::init was not called")
            .serve(&req, &certificate)
    })
}
